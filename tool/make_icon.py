"""Draws the reLiveTV icon: a white TV outline with "rL" inside, on black.

Re-run after changing the drawing:  python3 tool/make_icon.py
Writes Android launcher icons (adaptive + legacy square/round) and a Linux icon.
Needs Pillow and the DejaVu Sans Bold font (Debian/Ubuntu: fonts-dejavu-core).
"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "android/app/src/main/res"
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
WHITE, BLACK = (255, 255, 255, 255), (0, 0, 0, 255)
SS = 4  # supersampling for smooth edges


def tv(size: int, scale: float, background) -> Image.Image:
    """TV drawn in a box `scale` x size, centred. The whole drawing (screen
    corners included) fits inside a circle of diameter ~1.1 x box, so it
    survives circle, squircle and rounded-square masks."""
    S = size * SS
    img = Image.new("RGBA", (S, S), background or (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    box = S * scale
    ox = oy = (S - box) / 2

    def p(x, y):  # unit coords (0..1 in the box) → pixels
        return (ox + x * box, oy + y * box)

    stroke = round(0.06 * box)
    # antennas
    for tip in (0.33, 0.67):
        d.line([p(0.5, 0.25), p(tip, 0.07)], fill=WHITE, width=stroke)
    # screen
    d.rounded_rectangle([p(0.06, 0.25), p(0.94, 0.83)], radius=0.1 * box, outline=WHITE, width=stroke)
    # stand
    d.line([p(0.34, 0.93), p(0.66, 0.93)], fill=WHITE, width=stroke)
    # "rL", centred in the screen
    font = ImageFont.truetype(FONT, round(0.34 * box))
    cx, cy = p(0.5, 0.54)
    d.text((cx, cy), "rL", font=font, fill=WHITE, anchor="mm")
    return img.resize((size, size), Image.LANCZOS)


def circle(img: Image.Image) -> Image.Image:
    mask = Image.new("L", (img.width * SS, img.height * SS), 0)
    ImageDraw.Draw(mask).ellipse([0, 0, mask.width - 1, mask.height - 1], fill=255)
    out = Image.new("RGBA", img.size, (0, 0, 0, 0))
    out.paste(img, mask=mask.resize(img.size, Image.LANCZOS))
    return out


def main():
    densities = {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}
    for name, f in densities.items():
        folder = RES / f"mipmap-{name}"
        folder.mkdir(parents=True, exist_ok=True)
        legacy = round(48 * f)  # pre-Android 8 launchers
        tv(legacy, 0.7, BLACK).save(folder / "ic_launcher.png")
        circle(tv(legacy, 0.7, BLACK)).save(folder / "ic_launcher_round.png")
        # Android 8+: adaptive icon layers, 108dp with the safe zone in the middle 66dp
        tv(round(108 * f), 0.54, None).save(folder / "ic_launcher_foreground.png")

    anydpi = RES / "mipmap-anydpi-v26"
    anydpi.mkdir(exist_ok=True)
    adaptive = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/make_icon.py -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@mipmap/ic_launcher_foreground"/>
    <monochrome android:drawable="@mipmap/ic_launcher_foreground"/>
</adaptive-icon>
"""
    for n in ("ic_launcher.xml", "ic_launcher_round.xml"):
        (anydpi / n).write_text(adaptive)
    (RES / "values/ic_launcher_background.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="ic_launcher_background">#000000</color>\n</resources>\n'
    )

    linux = ROOT / "linux/relivetv.png"
    tv(256, 0.7, BLACK).save(linux)
    print("icons written")


if __name__ == "__main__":
    main()
